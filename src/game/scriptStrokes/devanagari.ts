// Hand-made: there is no open stroke-order dataset for Devanagari. The order follows the rule taught in
// Indian primary schools (NCERT Hindi primers, "Varnamala" copybooks): first the body of the letter,
// starting at its top-left / main curve, top to bottom, left to right; then the vertical bar (पाई /
// खड़ी पाई); the headline (शिरोरेखा) comes last, drawn left to right. Signs that sit on top of the
// headline (the hooks of ई ऐ ओ औ) are added after it, like the matras on a written word. Letters whose
// top-left loop stands on its own (थ ध भ श) get the headline only over the bar part.
// The shapes trace the app's Devanagari font (Baloo 2, public/fonts/devanagari.woff2).
//
// Sources:
//   - Introduction to the Hindi script, writing order "first strokes left to right, then the down
//     strokes, finally the head stroke": https://www.scribd.com/document/455371143/HIN11-Script-Intro-pdf
//   - Omniglot Devanagari chart: https://www.omniglot.com/charts/devanagari.pdf
//   - Devanagari overview (headline breaks at the loop letters): https://motaitalic.github.io/devanagari-documentation/languages/devanagari-overview/devanagari-overview.html
//
// No per-letter chart was found: start points of e.g. त ल ज च and the letters hanging from the headline
// (इ ई ड ङ झ ट ठ ढ द ह) are a choice and should be checked by a Hindi teacher.
//
