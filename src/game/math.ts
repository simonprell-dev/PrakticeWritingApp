/** HSL (h 0..360, s,l 0..1) to CSS */
export const hsl = (h: number, s: number, l: number, a = 1) =>
  `hsla(${((h % 360) + 360) % 360},${Math.round(clamp(s) * 100)}%,${Math.round(clamp(l) * 100)}%,${a})`;
